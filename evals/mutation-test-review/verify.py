"""Verifies each case's answer key against real mutation runs.

For every case this builds the fixture (without the skill), checks that the
tests pass, runs the mutation tool over the whole crate/package, and then
runs the case's `verify` checks:

  {"defect": id, "tool": "<regex>"}            some non-killed tool mutant matches
  {"defect": id, "hand": {file, find, replace}} applying the edit leaves the tests green
  {"defect": id, "revert": [files]}            the change's tests pass on the base version of these files
  {"control_min_score": 1.0}                   the tool score is at least this

Usage: python3 verify.py [case ...] [--explore] [-j N]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import fixture

SUMMARIZE = fixture.DEFAULT_SKILL_DIR / "scripts" / "summarize.py"
DEFAULT_GROUND_TRUTH_NOTE = "Whole-crate/package run of the mutation tool on the fixture, generated by verify.py."


def sh(cmd: list[str], cwd: Path, timeout: int = 900) -> subprocess.CompletedProcess:
  # a shared CARGO_TARGET_DIR lets parallel cargo-mutants runs overwrite each other's builds
  env = {name: value for name, value in os.environ.items() if name != "CARGO_TARGET_DIR"}
  return subprocess.run(cmd, cwd=cwd, check=False, capture_output=True, text=True, timeout=timeout, env=env)


def run_tests(
  repo: Path, lang: str, only: str | None = None, cmd: list[str] | None = None
) -> subprocess.CompletedProcess:
  if cmd:
    return sh(cmd, repo)

  if lang == "rust":
    return sh(["cargo", "test", "-q", *([only] if only else [])], repo)

  return sh(["npx", "vitest", "run", *(["-t", only] if only else [])], repo)


def mutate(repo: Path, lang: str, work: Path, in_place: bool = False) -> dict:
  if lang == "rust":
    result = sh(
      ["cargo", "mutants", "--gitignore", "true", "-o", str(work), "-j", "2"],
      repo,
      timeout=1800,
    )
    report = work / "mutants.out" / "outcomes.json"
  else:
    config = {
      "testRunner": "vitest",
      "mutate": ["src/**/*.ts"],
      "reporters": ["json"],
      "jsonReporter": {"fileName": str(work / "mutation.json")},
      "coverageAnalysis": "perTest",
      "concurrency": 2,
      "tempDirName": str(work / ".stryker-tmp"),
      "vitest": {"related": False},
      "inPlace": in_place,
    }
    (work / "stryker.config.json").write_text(json.dumps(config))

    result = sh(
      ["npx", "stryker", "run", str(work / "stryker.config.json")],
      repo,
      timeout=1800,
    )
    report = work / "mutation.json"

  if not report.exists():
    raise RuntimeError(f"mutation run produced no report:\n{result.stdout[-3000:]}\n{result.stderr[-3000:]}")

  summary = sh([sys.executable, str(SUMMARIZE), str(report), "--format", "json"], repo)

  return json.loads(summary.stdout)


def apply_hand(repo: Path, edits: dict | list[dict]) -> dict[str, str]:
  """Applies one or more find/replace edits; returns the original file texts."""
  originals: dict[str, str] = {}

  for edit in edits if isinstance(edits, list) else [edits]:
    path = repo / edit["file"]
    originals.setdefault(edit["file"], path.read_text())
    text = path.read_text()

    if text.count(edit["find"]) != 1:
      raise ValueError(f"hand mutation find string must occur once in {edit['file']}: {edit['find']!r}")

    path.write_text(text.replace(edit["find"], edit["replace"]))

  return originals


def verify_case(case_id: str, explore: bool) -> dict:
  work = Path(tempfile.mkdtemp(prefix=f"verify-{case_id}-"))
  root = work / "repo"
  case = fixture.build(case_id, root, skill_dir=None)
  repo = root / case.get("pkg", ".")
  lang = case["lang"]
  result = {"case": case_id, "ok": True, "checks": []}

  base = run_tests(repo, lang)

  if base.returncode != 0:
    return {
      **result,
      "ok": False,
      "error": "tests fail on the fixture:\n" + base.stdout[-2000:] + base.stderr[-2000:],
    }

  summary = mutate(repo, lang, work, case.get("verify_in_place", False))
  survivors = [mutant for mutant in summary["mutants"] if mutant["status"] not in ("killed", "timeout", "error")]

  result["counts"] = summary["counts"]
  result["score"] = summary.get("score")
  result["survivors"] = [
    f"{Path(mutant['file']).name}:{mutant['line']} [{mutant['status']}] {mutant['description']}" for mutant in survivors
  ]
  result["timeouts"] = [
    f"{Path(mutant['file']).name}:{mutant['line']} [timeout] {mutant['description']}"
    for mutant in summary["mutants"]
    if mutant["status"] == "timeout"
  ]

  for check in case.get("verify", []):
    entry = {**check}

    if "tool" in check:
      pattern = re.compile(check["tool"])
      entry["pass"] = any(pattern.search(survivor) for survivor in result["survivors"])
    elif "hand" in check:
      originals = apply_hand(repo, check["hand"])

      try:
        test_run = run_tests(repo, lang, check.get("only"), check.get("cmd"))
        green = test_run.returncode == 0
        entry["pass"] = green if check.get("expect", "pass") == "pass" else not green
      finally:
        for file, text in originals.items():
          (repo / file).write_text(text)
    elif "revert" in check:
      originals = {file: (repo / file).read_text() for file in check["revert"]}

      for file in check["revert"]:
        base_path = (repo / file).relative_to(root)
        (repo / file).write_text(fixture.git(repo, "show", f"main:{base_path}"))

      try:
        test_run = run_tests(repo, lang, check.get("only"), check.get("cmd"))
        entry["pass"] = test_run.returncode == 0
      finally:
        for file, text in originals.items():
          (repo / file).write_text(text)
    elif "baseline" in check:
      # the plain test command (or check["cmd"]) must report this many tests / succeed
      test_run = run_tests(repo, lang, None, check.get("cmd"))
      output = test_run.stdout + test_run.stderr
      entry["pass"] = test_run.returncode == 0 and re.search(check["baseline"], output) is not None

      if not entry["pass"]:
        entry["output"] = output[-2000:]
    elif "timeouts_min" in check:
      timeouts = summary["counts"].get("timeout", 0)
      entry["pass"] = timeouts >= check["timeouts_min"]
    elif "control_min_score" in check:
      entry["pass"] = (summary.get("score") or 0) >= check["control_min_score"]

    result["checks"].append(entry)
    result["ok"] &= entry["pass"]

  covered = {check["defect"] for check in case.get("verify", []) if "defect" in check}
  missing = [defect["id"] for defect in case["defects"] if defect["id"] not in covered]

  if missing:
    result["ok"] = False
    result["unverified_defects"] = missing

  if not explore:
    shutil.rmtree(work, ignore_errors=True)
  else:
    result["work"] = str(work)

  return result


def safe_verify(case_id: str, explore: bool) -> dict:
  try:
    return verify_case(case_id, explore)
  except Exception as error:  # noqa: BLE001 -- one crashed case must not discard the other cases' results
    return {
      "case": case_id,
      "ok": False,
      "checks": [],
      "error": f"{type(error).__name__}: {error}"[-3000:],
    }


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)

  parser.add_argument("cases", nargs="*")
  parser.add_argument("--explore", action="store_true", help="print survivors and keep the work dir")
  parser.add_argument("-j", type=int, default=3)
  parser.add_argument(
    "--write-ground-truth",
    action="store_true",
    help="save each passing case's tool survivors to cases/<id>/ground_truth.json for the judge",
  )

  args = parser.parse_args()

  cases = args.cases or fixture.list_cases()

  with ThreadPoolExecutor(args.j) as pool:
    results = list(pool.map(lambda case_id: safe_verify(case_id, args.explore), cases))

  for result in results:
    if args.write_ground_truth and result["ok"]:
      ground_truth = {key: result[key] for key in ("counts", "score", "survivors", "timeouts")}
      ground_truth["note"] = fixture.load_case(result["case"]).get("ground_truth_note", DEFAULT_GROUND_TRUTH_NOTE)
      ground_truth_path = fixture.CASES_DIR / result["case"] / "ground_truth.json"
      ground_truth_path.write_text(json.dumps(ground_truth, indent=2) + "\n")

    status = "OK" if result["ok"] else "FAIL"

    print(f"\n== {result['case']}: {status}  counts={result.get('counts')} score={result.get('score')}")

    if result.get("error"):
      print(result["error"])

    for check in result["checks"]:
      label = check.get("defect", "control")

      what = next(
        (
          check[key]
          for key in ("tool", "hand", "revert", "baseline", "timeouts_min", "control_min_score")
          if key in check
        ),
        None,
      )

      print(f"  [{'pass' if check['pass'] else 'FAIL'}] {label}: {what}")

      if check.get("output"):
        print("    " + check["output"].replace("\n", "\n    "))

    if result.get("unverified_defects"):
      print(f"  unverified defects: {result['unverified_defects']}")

    if args.explore:
      for survivor in result.get("survivors", []):
        print(f"    {survivor}")

  sys.exit(0 if all(result["ok"] for result in results) else 1)


if __name__ == "__main__":
  main()
